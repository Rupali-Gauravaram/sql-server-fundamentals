---23. Give the total weekly sales value with the date and product ID details. Useroll-up to pull the data in hierarchical order.

SELECT DATEPART(YEAR, [Date]) [Year], 
       DATEPART(WEEK, [Date]) Week_no, 
       SUM(Sales) weekly_sales 
FROM fact
GROUP BY ROLLUP (DATEPART(YEAR, [Date]), DATEPART(WEEK, [Date]))
ORDER BY DATEPART(YEAR, [Date]), DATEPART(WEEK, [Date])

