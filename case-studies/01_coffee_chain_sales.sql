---19. If there is an increase in sales of 5%, calculate the increasedsales.

CREATE FUNCTION get_increase_sales()
RETURNS TABLE
AS 
RETURN
(
  SELECT ProductId, Sales, Sales*1.05 AS increased_sales   --->increased_sales = Sales + Sales*0.05 = Sales*1.05
  FROM fact
)

SELECT * FROM get_increase_sales()

